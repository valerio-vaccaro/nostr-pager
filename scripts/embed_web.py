#!/usr/bin/env python3
"""Embed local-only browser assets for offline firmware builds."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
output = '// Generated by scripts/embed_web.py. Edit assets/web/ instead.\n'
for symbol, filename in [('webHead', 'head.html'), ('webScript', 'app.js')]:
    value = (root / 'assets/web' / filename).read_text()
    assert ')WEB"' not in value
    output += f'static const char {symbol}[] = R"WEB({value})WEB";\n'
(root / 'include/web_assets.h').write_text(output)
