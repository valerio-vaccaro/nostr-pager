#!/usr/bin/env python3
"""Refresh the ESP32 trust bundle from a trusted system CA file (requires cryptography)."""
import argparse, pathlib, struct
from cryptography import x509
from cryptography.hazmat.primitives import serialization
parser=argparse.ArgumentParser()
parser.add_argument('pem', nargs='?', default='/etc/ssl/certs/ca-certificates.crt')
args=parser.parse_args()
certs=x509.load_pem_x509_certificates(pathlib.Path(args.pem).read_bytes())
records={}
for cert in certs:
    subject=cert.subject.public_bytes()
    key=cert.public_key().public_bytes(serialization.Encoding.DER,serialization.PublicFormat.SubjectPublicKeyInfo)
    records[subject]=key
bundle=struct.pack('>H',len(records))
for subject,key in sorted(records.items()):
    bundle+=struct.pack('>HH',len(subject),len(key))+subject+key
pathlib.Path('include/ca_bundle.h').write_text('// System trust roots; generated by scripts/make_ca_bundle.py\n#pragma once\n#include <stdint.h>\nstatic const uint8_t caBundle[] = {\n'+''.join('    '+','.join(f'0x{v:02x}' for v in bundle[i:i+16])+',\n' for i in range(0,len(bundle),16))+'};\n')
print(f'{len(records)} roots, {len(bundle)} bytes')
